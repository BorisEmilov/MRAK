/**
 * Icon pipeline (docs/ui/icons.md): icons/manifest.json (our name → game-icons.net source) →
 * one SVG sprite, a typed name list and the documentation table. Pure: the CLI writes the files,
 * the test checks they are up to date.
 */
export const ICON_CATEGORIES = [
  'resource',
  'phase',
  'action',
  'ui',
  'attribute',
  'skill',
  'calling',
  'tree',
  'talent',
  'omen',
  'debt',
  'building',
  'villager-state',
  'event',
  'achievement',
  'faction',
  'poi',
  'need',
  'task',
  'item',
  'collection',
  'layer',
  'gear',
  'check',
  'choice',
] as const;
export type IconCategory = (typeof ICON_CATEGORIES)[number];

export interface ManifestIcon {
  name: string;
  category: IconCategory;
  source: string;
  author: string;
  meaning: string;
}

export interface IconSet {
  width?: number;
  height?: number;
  icons: Record<string, { body: string; width?: number; height?: number }>;
}

const NAME = /^[a-z][a-z-]*\.[a-z0-9][a-z0-9-]*$/;

/** The author's display name as credited on game-icons.net. */
export const AUTHOR_NAMES: Readonly<Record<string, string>> = {
  lorc: 'Lorc',
  delapouite: 'Delapouite',
  skoll: 'Skoll',
  sbed: 'Sbed',
  'caro-asercion': 'Caro Asercion',
  willdabeast: 'Willdabeast',
  generalace135: 'GeneralAce135',
  darkzaitzev: 'DarkZaitzev',
};

export function parseManifest(raw: unknown): ManifestIcon[] {
  if (typeof raw !== 'object' || raw === null || !('icons' in raw) || !Array.isArray(raw.icons))
    throw new Error('manifest: missing "icons" array');
  const seen = new Set<string>();
  return raw.icons.map((value: unknown, i: number) => {
    const icon = value as Partial<ManifestIcon>;
    const where = `manifest.icons[${String(i)}]`;
    if (typeof icon.name !== 'string' || !NAME.test(icon.name))
      throw new Error(`${where}: name must look like "category.id"`);
    if (seen.has(icon.name)) throw new Error(`${where}: duplicate name ${icon.name}`);
    seen.add(icon.name);
    if (!ICON_CATEGORIES.includes(icon.category as IconCategory))
      throw new Error(`${where}: unknown category ${String(icon.category)}`);
    if (!icon.name.startsWith(`${String(icon.category)}.`))
      throw new Error(`${where}: name must start with its category`);
    for (const field of ['source', 'author', 'meaning'] as const)
      if (typeof icon[field] !== 'string' || icon[field] === '')
        throw new Error(`${where}: missing ${field}`);
    if (!icon.author || !(icon.author in AUTHOR_NAMES)) throw new Error(`${where}: unknown author`);
    return icon as ManifestIcon;
  });
}

/** `talent.red-thread` → `mrak-talent--red-thread` (a valid, unique XML id). */
export function symbolId(name: string): string {
  return `mrak-${name.replace('.', '--')}`;
}

export function buildSprite(icons: readonly ManifestIcon[], set: IconSet): string {
  const symbols = icons.map((icon) => {
    const src = set.icons[icon.source];
    if (!src) throw new Error(`icon source not found: ${icon.source} (${icon.name})`);
    const w = src.width ?? set.width ?? 512;
    const h = src.height ?? set.height ?? 512;
    // game-icons paths already use fill="currentColor": the palette colours them through CSS.
    return `<symbol id="${symbolId(icon.name)}" viewBox="0 0 ${String(w)} ${String(h)}">${src.body}</symbol>`;
  });
  return [
    '<!-- Generated by packages/ui-kit/scripts/build-icons.ts. Do not edit. -->',
    '<!-- Icons: game-icons.net, CC BY 3.0 — authors listed in docs/ui/icons.md. -->',
    `<svg xmlns="http://www.w3.org/2000/svg">${symbols.join('')}</svg>`,
    '',
  ].join('\n');
}

export function buildNames(icons: readonly ManifestIcon[]): string {
  const lines = [
    '// Generated by packages/ui-kit/scripts/build-icons.ts from icons/manifest.json. Do not edit.',
    '',
    'export const ICON_NAMES = [',
    ...icons.map((i) => `  '${i.name}',`),
    '] as const;',
    '',
    'export type IconName = (typeof ICON_NAMES)[number];',
    '',
    '/** Category, source icon and author of every icon (for galleries and credits). */',
    'export const ICON_INFO: Readonly<',
    '  Record<IconName, { category: string; source: string; author: string; meaning: string }>',
    '> = {',
    ...icons.map(
      (i) =>
        `  '${i.name}': { category: '${i.category}', source: '${i.source}', author: '${AUTHOR_NAMES[i.author] ?? i.author}', meaning: ${JSON.stringify(i.meaning)} },`,
    ),
    '};',
    '',
    '/** Icon authors to credit (game-icons.net, CC BY 3.0). */',
    `export const ICON_AUTHORS = ${JSON.stringify([...new Set(icons.map((i) => AUTHOR_NAMES[i.author] ?? i.author))].sort())} as const;`,
    '',
  ];
  return lines.join('\n');
}

export function buildDocs(icons: readonly ManifestIcon[]): string {
  const authors = [...new Set(icons.map((i) => AUTHOR_NAMES[i.author] ?? i.author))].sort();
  const out = [
    '# Icons',
    '',
    'Status: v1 (provisional set) · Generated by `pnpm --filter @mrak/ui-kit icons` from',
    '`packages/ui-kit/icons/manifest.json` — do not edit by hand · Back to [UI index](README.md)',
    '',
    '## Licence and attribution',
    '',
    `All ${String(icons.length)} icons come from [game-icons.net](https://game-icons.net), licensed`,
    '[CC BY 3.0](https://creativecommons.org/licenses/by/3.0/). They are **recoloured** (single',
    'colour through `currentColor`, palette from the [design system](design-system.md)); no other',
    'changes. Attribution is required and shown in the in-game **Credits** screen and here:',
    '',
    `> Icons by ${authors.join(', ')} — from game-icons.net, licensed under CC BY 3.0.`,
    '',
    'The set is provisional: final art may replace it, keeping the same names.',
    '',
    '## Usage',
    '',
    '```tsx',
    '<Icon name="resource.sanity" label={t("stat.sanity.name")} description={t("stat.sanity.desc")} />',
    '<Icon name="action.talk" decorative /> // only next to a visible text label',
    '```',
    '',
    'Content icons follow the convention `<category>.<content id>` (`talent.red-thread`,',
    '`attribute.vigor`, `achievement.first-night`…); a game test fails if a talent, attribute, skill,',
    'calling, tree, building, debt source or achievement has no icon.',
  ];
  for (const category of new Set(icons.map((i) => i.category))) {
    out.push(
      '',
      `## ${category}`,
      '',
      '| Name | Meaning | Source | Author |',
      '| --- | --- | --- | --- |',
    );
    for (const i of icons.filter((x) => x.category === category)) {
      out.push(
        `| \`${i.name}\` | ${i.meaning.replace(/\\/g, '\\\\').replace(/\|/g, '\\|')} | [${i.source}](https://game-icons.net/1x1/${i.author}/${i.source}.html) | ${AUTHOR_NAMES[i.author] ?? i.author} |`,
      );
    }
  }
  out.push('');
  return out.join('\n');
}
